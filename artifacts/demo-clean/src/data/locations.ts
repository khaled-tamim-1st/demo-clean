export function getGovernorateBySlug(slug: string): GovernorateItem | undefined {
  return governoratesData.find((gov) => gov.slug === slug);
}

export function getAllGovernorateSlugs(): string[] {
  return governoratesData.map((gov) => gov.slug);
}

export function getAreaBySlug(govSlug: string, areaSlug: string): AreaItem | undefined {
  const gov = getGovernorateBySlug(govSlug);
  if (!gov) return undefined;
  return gov.areas.find((area) => area.slug === areaSlug);
}

export function getAllAreasWithGov(): { govSlug: string; areaSlug: string; area: AreaItem }[] {
  const result: { govSlug: string; areaSlug: string; area: AreaItem }[] = [];
  for (const gov of governoratesData) {
    for (const area of gov.areas) {
      result.push({
        govSlug: gov.slug,
        areaSlug: area.slug,
        area
      });
    }
  }
  return result;
}
